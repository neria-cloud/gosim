package routegen

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

// renderDispatch keeps the routing mechanics generated from the same ordered
// parameter/result schema as callers. Exceptional lifecycle and borrowed-memory
// operations remain explicit; a new route cannot silently choose a fallback.
func renderDispatch(m Manifest) ([]byte, error) {
	if err := m.Validate(); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString(`// Code generated by gosim-gen. DO NOT EDIT.
package kernel
import (
 "fmt"
 "syscall"

 "github.com/neria-cloud/gosim/internal/contracts"
)

//go:norace
func (d *Dispatcher) decode(inv *Invocation) (Result,bool,error) {
 if err:=validateRoutePayload(inv); err!=nil { return Result{},false,err }
 d.kernel.countSyscall(inv)
 k,ctx:=d.kernel,inv.Context
 switch inv.Route {
`)
	for _, r := range m.Routes {
		fmt.Fprintf(&b, "case Route%s:\n", r.Name)
		if len(r.Inputs) > 0 {
			fmt.Fprintf(&b, "p:=inv.Args[0].(%sRequest)\n", r.Name)
		}
		fmt.Fprintf(&b, "var out %sResult\n", r.Name)
		var args []string
		for _, field := range r.Inputs {
			args = append(args, "p."+field.Name)
		}
		var outputs []string
		for _, field := range r.Results {
			outputs = append(outputs, "out."+field.Name)
		}
		call := func(receiver, method string, parameters []string, hasError bool) {
			lhs := append([]string(nil), outputs...)
			if hasError {
				b.WriteString("var err error\n")
				lhs = append(lhs, "err")
			}
			if len(lhs) > 0 {
				fmt.Fprintf(&b, "%s = ", strings.Join(lhs, ","))
			}
			fmt.Fprintf(&b, "%s.%s(%s)\n", receiver, method, strings.Join(parameters, ","))
		}
		switch r.Kind {
		case "syscall":
			receiver := "k"
			if r.Owner != "kernel" {
				service := "Filesystem"
				if r.Owner == "net" {
					service = "Network"
				}
				fmt.Fprintf(&b, "service,serviceErr:=k.%s(ctx)\nif serviceErr!=nil {return Result{},false,serviceErr}\n", service)
				receiver = "service"
			}
			switch r.Name {
			case "Getpid":
				call(receiver, r.Name, []string{"ctx"}, false)
				b.WriteString("return syscallRouteResult(out,nil)\n")
			case "FcntlLock":
				b.WriteString(`if p.Lock.UnsafePointer()==nil {return Result{},false,invalidPayload(ctx,"nil file-lock view")}
value:=p.Lock.Get()
err:=service.FcntlLock(ctx,p.FD,p.Command,&value)
if err==nil {p.Lock.Set(value)}
return syscallRouteResult(out,err)
`)
			default:
				method := r.Name
				switch method {
				case "Close":
					method = "CloseFD"
				case "Writev":
					method = "Write"
				}
				call(receiver, method, append([]string{"ctx"}, args...), true)
				if r.Name == "Sync" {
					b.WriteString("if request,ok:=err.(*contracts.CrashRequest); ok {return Result{},true,request}\n")
				}
				b.WriteString("return syscallRouteResult(out,err)\n")
			}
		case "poll":
			if r.Name == "PollOpen" {
				b.WriteString("handle,err:=k.PollOpen(ctx,p.FD)\nout.Handle=handle\n")
			} else {
				fmt.Fprintf(&b, "err:=k.%s(%s)\n", r.Name, strings.Join(append([]string{"ctx"}, args...), ","))
			}
			if r.Name == "PollWait" {
				b.WriteString("if err==errPending {return Result{},true,nil}\n")
			}
			b.WriteString("out.Code,err=pollCode(err)\nreturn controlRouteResult(out,err)\n")
		case "wait":
			b.WriteString("_ = out\nreturn d.decodeMachineWait(ctx,p.Machine)\n")
		case "self":
			b.WriteString("_ = out\nif err:=k.exitSelf(ctx,p.Kind); err!=nil {return controlRouteResult(out,err)}\nreturn Result{},true,nil\n")
		case "control":
			receiver, method := "k", r.Name
			if strings.HasPrefix(r.Name, "FS") || strings.HasPrefix(r.Name, "Net") {
				prefix, service := "FS", "FilesystemControl"
				if strings.HasPrefix(r.Name, "Net") {
					prefix, service = "Net", "NetworkControl"
				}
				run := "ctx.Epoch.Machine.RunID"
				for _, f := range r.Inputs {
					if f.Name == "Machine" {
						run = "p.Machine.RunID"
					}
					if f.Name == "RunID" {
						run = "p.RunID"
					}
				}
				fmt.Fprintf(&b, "service,serviceErr:=k.%s(ctx,%s)\nif serviceErr!=nil {return controlRouteResult(out,serviceErr)}\n", service, run)
				receiver, method = "service", strings.TrimPrefix(r.Name, prefix)
				args = nil
				for _, f := range r.Inputs {
					if f.Name != "RunID" && f.Name != "SnapshotRunID" {
						args = append(args, "p."+f.Name)
					}
				}
				if r.Name == "FSRestore" {
					b.WriteString("if p.SnapshotRunID!=p.Machine.RunID {return controlRouteResult(out,contracts.ErrWrongRun)}\n")
				}
			}
			if r.Name == "Require" {
				b.WriteString("if p.Feature!=contracts.RT && p.Feature!=contracts.FS && p.Feature!=contracts.Net {return Result{},false,invalidPayload(ctx,\"invalid feature\")}\nk.Require(ctx,p.Feature,p.Operation)\nreturn controlRouteResult(out,nil)\n")
			} else if r.Name == "Info" {
				b.WriteString("out=k.runInfo()\nreturn controlRouteResult(out,nil)\n")
			} else {
				if method == "State" {
					method = "MachineState"
				}
				call(receiver, method, args, true)
				b.WriteString("return controlRouteResult(out,err)\n")
			}
		default:
			return nil, fmt.Errorf("unimplemented route kind %s", r.Kind)
		}
	}
	b.WriteString(`}
 return Result{},false,invalidPayload(ctx,"unreachable route")
}

func invalidPayload(ctx contracts.CallContext,message string) error {
 return &contracts.Failure{Code:contracts.InvalidABI,Diagnostic:contracts.Diagnostic{Operation:"decode",Epoch:ctx.Epoch,Message:message}}
}
func syscallRouteResult(value any,err error) (Result,bool,error) {
 if err==nil {return Result{Value:value},false,nil}
 errno,ok:=err.(syscall.Errno)
 if !ok {return Result{},false,fmt.Errorf("unmodeled syscall error: %w",err)}
 return Result{Errno:uintptr(errno)},false,nil
}
func controlRouteResult(value any,err error) (Result,bool,error) {
 if failure,ok:=err.(*contracts.Failure); ok {return Result{},false,failure}
 if err!=nil {return Result{Value:err},false,nil}
 return Result{Value:value},false,nil
}
`)
	return format.Source(b.Bytes())
}
