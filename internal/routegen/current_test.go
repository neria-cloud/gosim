// Native test jobs exercise the compiler Go selected for that job. They never
// install or execute another family internally.
func currentGeneration(t *testing.T) (buildspec.Toolchain, spec.Profile, GenerateOptions) {
	t.Helper()
	r, err := buildcfg.ResolveRunningProcess(t.Context(), "")
	if err != nil {
		t.Fatal(err)
	}
	v, err := buildspec.ParseGoVersion(r.Toolchain.Version)
	if err != nil {
		t.Fatal(err)
	}
	family, err := buildspec.LookupFamily(v)
	if err != nil {
		t.Fatal(err)
	}
	entry, err := catalog.Lookup(family.Profile)
	if err != nil {
		t.Fatal(err)
	}
	p, err := entry.Descriptor(r.Toolchain.HostArch)
	if err != nil {
		t.Fatal(err)
	}
	return r.Toolchain, p, GenerateOptions{RefreshOrigin: r.Toolchain.Version != entry.Origin().BaselineToolchain}
}

func otherFamily(current string) string {
	for _, f := range buildspec.SupportedFamilies() {
		if f.Profile != current {
			return f.Profile
		}
	}
	panic("fixture requires another registered family")
}

// Executable output must match reviewed adapters on every supported patch.
// Generation provenance is patch-specific; normalize only those recorded fields
// and the compiler comment, without hiding changes in generated declarations.
func assertGeneratedMatchesBaseline(t *testing.T, tc buildspec.Toolchain, name string, actual []byte) {
	t.Helper()
	if strings.HasSuffix(name, "/origin.json") {
		var origin spec.Origin
		if err := json.Unmarshal(actual, &origin); err != nil {
			t.Fatal(err)
		}
		if err := spec.VerifyBaselineOrigin(tc, origin); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(filepath.Join("../..", name))
	if err != nil {
		t.Fatal(err)
	}
	if strings.HasSuffix(name, ".go") {
		prefix := []byte("// Code generated by gosim-gen from ")
		if bytes.HasPrefix(actual, prefix) && bytes.HasPrefix(want, prefix) {
			actual = actual[bytes.IndexByte(actual, '\n')+1:]
			want = want[bytes.IndexByte(want, '\n')+1:]
		}
	} else if strings.Contains(name, "/profile/routes_") {
		var a, b GenerationRecord
		if err := json.Unmarshal(actual, &a); err != nil {
			t.Fatal(err)
		}
		if err := json.Unmarshal(want, &b); err != nil {
			t.Fatal(err)
		}
		if a.GeneratedWith != tc.Version || !buildspec.ValidDigest(a.AdapterDigest) || !buildspec.ValidDigest(a.OriginDigest) {
			t.Fatal("invalid actual generation provenance", a)
		}
		a.GeneratedWith, b.GeneratedWith = "", ""
		a.OriginDigest, b.OriginDigest = "", ""
		// The adapter digest includes the compiler comment compared above.
		a.AdapterDigest, b.AdapterDigest = "", ""
		actual, _ = json.Marshal(a)
		want, _ = json.Marshal(b)
	}
	if !bytes.Equal(actual, want) {
		t.Fatalf("generated declarations or route semantics changed in %s", name)
	}
}
