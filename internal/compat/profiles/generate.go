package profiles

import (
	"bytes"
	"context"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/neria-cloud/gosim/internal/buildspec"
	"github.com/neria-cloud/gosim/internal/compat/spec"
)

const generatedHeader = "// Code generated by gosim-gen profiles; DO NOT EDIT.\n"

// GenerateMetadata uses checkout definitions, including families absent from the
// running binary's registry. Write mode can bootstrap before provenance exists.
func GenerateMetadata(ctx context.Context, root string, check bool) error {
	defs, err := spec.LoadDefinitions(os.DirFS(filepath.Join(root, "internal/compat/profiles")))
	if err != nil {
		return err
	}
	outputs, err := renderSupport(defs)
	if err != nil {
		return err
	}
	// Remove only obsolete generated family selectors, never arbitrary source files.
	selectors, err := filepath.Glob(filepath.Join(root, "internal/compat/selected/go*.go"))
	if err != nil {
		return err
	}
	for _, filename := range selectors {
		if !regexp.MustCompile(`^go1[0-9]+\.go$`).MatchString(filepath.Base(filename)) {
			continue
		}
		name := "internal/compat/selected/" + filepath.Base(filename)
		if _, ok := outputs[name]; ok {
			continue
		}
		if err := ctx.Err(); err != nil {
			return err
		}
		if check {
			return fmt.Errorf("stale selector %s", name)
		}
		data, err := os.ReadFile(filename)
		if err != nil {
			return err
		}
		if !bytes.Contains(data, []byte(generatedHeader)) {
			return fmt.Errorf("refusing to remove authored selector %s", name)
		}
		if err := os.Remove(filename); err != nil {
			return err
		}
	}
	if err := publishMetadata(ctx, root, outputs, check); err != nil {
		return err
	}
	revisions, err := renderRevisions(root, defs)
	if err != nil {
		return err
	}
	if err := publishMetadata(ctx, root, map[string][]byte{"internal/compat/profiles/revisions_gen.go": revisions}, check); err != nil {
		return err
	}
	if check {
		for _, d := range defs {
			if !d.Supported {
				continue
			}
			id := "go" + strings.ReplaceAll(d.Family, ".", "")
			if _, err := spec.LoadOrigin(os.DirFS(filepath.Join(root, "internal/compat/profiles")), id); err != nil {
				return err
			}
		}
	}
	return ctx.Err()
}

func publishMetadata(ctx context.Context, root string, outputs map[string][]byte, check bool) error {
	names := make([]string, 0, len(outputs))
	for name := range outputs {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		if err := ctx.Err(); err != nil {
			return err
		}
		filename := filepath.Join(root, filepath.FromSlash(name))
		old, err := os.ReadFile(filename)
		if err == nil && bytes.Equal(old, outputs[name]) {
			continue
		}
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		if check {
			return fmt.Errorf("stale/missing %s", name)
		}
		if err := os.MkdirAll(filepath.Dir(filename), 0o755); err != nil {
			return err
		}
		if err := replaceMetadata(ctx, filename, outputs[name]); err != nil {
			return err
		}
	}
	return nil
}

func replaceMetadata(ctx context.Context, filename string, data []byte) error {
	file, err := os.CreateTemp(filepath.Dir(filename), ".gosim-profiles-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err := file.Write(data); err != nil {
		file.Close()
		return err
	}
	if err := file.Chmod(0o644); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	return os.Rename(file.Name(), filename)
}

func orderedDefinitions(defs map[string]spec.FamilyDefinition) ([]spec.ResolvedFamily, error) {
	var rows []spec.ResolvedFamily
	for family := range defs {
		r, err := spec.ResolveDefinitions(defs, family)
		if err != nil {
			return nil, err
		}
		rows = append(rows, r)
	}
	slices.SortFunc(rows, func(a, b spec.ResolvedFamily) int { return len(a.Chain) - len(b.Chain) })
	return rows, nil
}

func renderSupport(defs map[string]spec.FamilyDefinition) (map[string][]byte, error) {
	rows, err := orderedDefinitions(defs)
	if err != nil {
		return nil, err
	}
	outputs := map[string][]byte{}
	table := generatedHeader + "\npackage buildspec\n\nvar families = []FamilySupport{\n"
	var intervals []string
	for _, r := range rows {
		if !r.Supported {
			continue
		}
		v, err := buildspec.ParseGoVersion("go" + r.Family + ".0")
		if err != nil {
			return nil, err
		}
		interval := fmt.Sprintf("go1.%d && !go1.%d", v.Minor, v.Minor+1)
		intervals = append(intervals, "("+interval+")")
		table += fmt.Sprintf("{Family: %q, Profile: %q},\n", r.Family, r.ProfileID)
		source := fmt.Sprintf("%s//go:build %s\n\npackage selected\n\nconst selectedProfile = %q\n", generatedHeader, interval, r.ProfileID)
		outputs["internal/compat/selected/"+r.ProfileID+".go"] = []byte(source)
	}
	if len(intervals) == 0 {
		return nil, fmt.Errorf("no supported family definitions")
	}
	outputs["internal/buildspec/families_gen.go"] = []byte(table + "}\n")
	for _, dir := range []string{"internal/compat/selected", "internal/compat/host", "internal/hostabi"} {
		source := fmt.Sprintf("%s//go:build !(%s)\n\npackage %s\n\nvar _ = GOSIM_UNSUPPORTED_GO_FAMILY\n", generatedHeader, strings.Join(intervals, " || "), filepath.Base(dir))
		outputs[dir+"/unsupported.go"] = []byte(source)
	}
	for name, data := range outputs {
		formatted, err := format.Source(data)
		if err != nil {
			return nil, err
		}
		outputs[name] = formatted
	}
	return outputs, nil
}

func renderRevisions(root string, defs map[string]spec.FamilyDefinition) ([]byte, error) {
	rows, err := orderedDefinitions(defs)
	if err != nil {
		return nil, err
	}
	source := generatedHeader + "\npackage profiles\n\nvar revisions = map[string]string{\n"
	for _, r := range rows {
		if !r.Supported {
			continue
		}
		revision, err := spec.SourceRevision(root, r.ProfileID)
		if err != nil {
			return nil, err
		}
		source += fmt.Sprintf("%q: %q,\n", r.ProfileID, revision)
	}
	return format.Source([]byte(source + "}\n"))
}
