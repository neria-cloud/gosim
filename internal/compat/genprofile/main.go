// Command genprofile updates source fingerprints after an adapter change. It does
// not rewrite ABI expectations, upstream origin hashes or certification records.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/neria-cloud/gosim/internal/buildspec"
	"github.com/neria-cloud/gosim/internal/compat/spec"
)

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "fail on stale source fingerprints")
	flag.Parse()
	for _, support := range buildspec.SupportedFamilies() {
		family := support.Profile
		revision, err := spec.SourceRevision(*root, family)
		if err != nil {
			fail(err)
		}
		path := filepath.Join(*root, "internal/compat", family, "profile/revision.go")
		data := []byte(fmt.Sprintf("// Code generated by genprofile; DO NOT EDIT.\n\npackage profile\n\nconst Revision = %q\n", revision))
		existing, readErr := os.ReadFile(path)
		if readErr == nil && string(existing) == string(data) {
			continue // Preserve mtimes used by the intermediate artifact cache.
		}
		if *check {
			fail(fmt.Errorf("stale %s; run go run ./internal/compat/genprofile", path))
		} else if err := os.WriteFile(path, data, 0o644); err != nil {
			fail(err)
		}
	}
}
func fail(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }
